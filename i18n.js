window.t=(s,v={})=>((LANG!=="en"&&T[LANG][s])||s).replace(/\{(\w)\}/g,(_,k)=>v[k]??"");

const SKIP=new Set(["SCRIPT","STYLE","TEXTAREA","svg"]);
const ATTRS=["placeholder","alt","aria-label"];
function setLang(lang){
  LANG=T[lang]||lang==="en"?lang:"en";
  const d=T[LANG]||{},tr=k=>LANG==="en"?k:d[k];
  document.documentElement.lang=LANG;
  const esc=x=>x.replace(/&/g,"&amp;").replace(/</g,"&lt;"),
        emph=x=>esc(x).replace(/\*(.+?)\*/g,"<em>$1</em>"),
        pick=en=>LANG==="en"?en:(d[en.replace(/\*/g,"")]||en);
  // headings carry their English (with *accent* marks) in data-em / data-words
  document.querySelectorAll("[data-em]").forEach(h=>{h.innerHTML=emph(pick(h.dataset.em))});
  document.querySelectorAll("[data-words]").forEach(h=>{
    h.innerHTML=pick(h.dataset.words).split(" ").map(x=>'<span class="w">'+emph(x)+"</span>").join(" ");
  });
  const w=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT,{acceptNode:n=>SKIP.has(n.parentNode.nodeName)||n.parentNode.closest("[data-words],[data-em]")?2:1});
  for(let n;(n=w.nextNode());){
    if(n._en===undefined)n._en=n.nodeValue;
    const k=n._en.trim(),v=k&&tr(k);
    n.nodeValue=v?n._en.replace(k,v.replace(/\*/g,"")):n._en;
  }
  document.querySelectorAll(ATTRS.map(a=>"["+a+"]").join(",")).forEach(el=>{
    el._en=el._en||{};
    for(const a of ATTRS)if(el.hasAttribute(a)){
      if(el._en[a]===undefined)el._en[a]=el.getAttribute(a);
      el.setAttribute(a,(tr(el._en[a])||el._en[a]).replace(/\*/g,""));
    }
  });
  document._enTitle=document._enTitle||document.title;
  document.title=(tr(document._enTitle)||document._enTitle).replace(/\*/g,"");
  document.querySelectorAll(".lang [data-lang]").forEach(b=>b.setAttribute("aria-current",b.dataset.lang===LANG));
  try{localStorage.setItem("lang",LANG)}catch(e){}
  document.dispatchEvent(new Event("langchange"));
}

// the "Language" menu: opens when the pointer is over it (or on a tap), and switches on a click
const menu=document.querySelector(".lang"),toggle=menu&&menu.querySelector(".lang-btn");
const openMenu=o=>{if(!menu)return;menu.classList.toggle("open",o);toggle.setAttribute("aria-expanded",o)};
if(menu){
  menu.addEventListener("mouseenter",()=>{menu.classList.remove("closed");toggle.setAttribute("aria-expanded",true)});
  menu.addEventListener("mouseleave",()=>{menu.classList.remove("closed");openMenu(false)});
  toggle.addEventListener("click",()=>{menu.classList.remove("closed");openMenu(!menu.classList.contains("open"))});
  menu.querySelectorAll("[data-lang]").forEach(b=>b.addEventListener("click",()=>{setLang(b.dataset.lang);openMenu(false);menu.classList.add("closed")}));
  document.addEventListener("click",e=>{if(!menu.contains(e.target))openMenu(false)});
  document.addEventListener("keydown",e=>{if(e.key==="Escape"&&menu.classList.contains("open")){openMenu(false);toggle.focus()}});
  menu.addEventListener("focusout",e=>{if(!menu.contains(e.relatedTarget))openMenu(false)});
}
